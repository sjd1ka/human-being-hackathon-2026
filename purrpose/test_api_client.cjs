const assert=require('node:assert/strict');
const {createPurrposeClient}=require('./web/api-client.js');
(async()=>{
 const calls=[];
 const api=createPurrposeClient({fetchImpl:async(path,options)=>{calls.push({path,options});return {ok:true,status:200,json:async()=>({status:'ok'})};}});
 await api.status();await api.supporter({city:'Ottawa'});await api.organization(['https://example.invalid/purrpose/maple']);
 await api.chat('session-one','How much?');await api.history();await api.demoUpdate('clarify','same-task');await api.debug();
 await api.runs();await api.run('x');
 assert.equal(calls.length,9);assert.equal(calls[0].options.method,'GET');
 for(const c of calls.slice(1,7))assert.equal(c.options.headers['X-Purrpose-Local'],'1');
 assert.deepEqual(JSON.parse(calls[3].options.body),{session_id:'session-one',message:'How much?'});
 assert.equal(JSON.parse(calls[5].options.body).request_id,'same-task');
 assert.equal(calls[7].path,'/api/runs');assert.deepEqual(JSON.parse(calls[7].options.body),{});
 assert.equal(calls[7].options.headers['X-Purrpose-Local'],'1');
 assert.equal(calls[8].path,'/api/runs/get');assert.deepEqual(JSON.parse(calls[8].options.body),{run_id:'x'});
 let count=0;const failed=createPurrposeClient({fetchImpl:async()=>{count++;return {ok:false,status:503,json:async()=>({error:'memory_unavailable'})};}});
 await assert.rejects(failed.supporter(),e=>e.code==='memory_unavailable'&&e.status===503);assert.equal(count,1);
 const timeout=createPurrposeClient({timeoutMs:5,fetchImpl:(_,o)=>new Promise((_,reject)=>o.signal.addEventListener('abort',()=>reject(Error('aborted'))))});
 await assert.rejects(timeout.chat('a','hi'),e=>e.code==='timeout_result_unknown');
 const malformed=createPurrposeClient({fetchImpl:async()=>({status:200,ok:true,json:async()=>{throw Error('bad');}})});
 await assert.rejects(malformed.status(),e=>e.code==='invalid_response');
 console.log('API client: nine route mappings, headers, error propagation, timeout and no-retry checks passed.');
})().catch(e=>{console.error(e);process.exit(1);});
